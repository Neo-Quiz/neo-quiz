/**
 * DEVELOPER TOOL, never run by the app: pins the Python interpreter and the
 * course libraries and writes apps/windows/electron/python/catalogue-data.ts.
 *
 * For each root package it runs the local `py -3.12 -m pip download` for
 * win_amd64 / CPython 3.12 (wheels only) into %TEMP%\nq-pin-python, reads
 * every wheel's METADATA (Requires-Dist evaluated for this platform, no
 * extras) to build `dependances`, then takes url / sha256 / size from the
 * PyPI JSON API for the exact wheel filename. The interpreter zip is
 * downloaded and hashed here.
 *
 *     node scripts/pin-python.mjs
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const RACINE = join(dirname(fileURLToPath(import.meta.url)), "..");
const SORTIE = join(RACINE, "apps/windows/electron/python/catalogue-data.ts");
const TMP = join(tmpdir(), "nq-pin-python");
const URL_INTERPRETE = "https://www.python.org/ftp/python/3.12.10/python-3.12.10-embed-amd64.zip";
const RACINES = [
	["torch", "torch==2.14.1"],
	["numpy", "numpy"],
	["pandas", "pandas"],
	["matplotlib", "matplotlib"],
	["scikit-learn", "scikit-learn"],
	["scipy", "scipy"],
	["seaborn", "seaborn"],
];
const IMPORTS = {
	torch: "torch", numpy: "numpy", pandas: "pandas", matplotlib: "matplotlib",
	sklearn: "scikit-learn", scipy: "scipy", seaborn: "seaborn",
};

const norm = (n) => n.toLowerCase().replace(/[-_.]+/g, "-");
const py = (args, opts = {}) =>
	execFileSync("py", ["-3.12", ...args], { encoding: "utf8", maxBuffer: 1 << 28, stdio: ["ignore", "pipe", "inherit"], ...opts });

/** Reads name, version and win_amd64 / py3.12 Requires-Dist of one wheel. */
const LIRE_ROUE = `
import sys, zipfile, json, email
from pip._vendor.packaging.requirements import Requirement
z = zipfile.ZipFile(sys.argv[1])
n = [x for x in z.namelist() if x.endswith(".dist-info/METADATA") and x.count("/") == 1][0]
m = email.message_from_bytes(z.read(n))
deps = []
for line in m.get_all("Requires-Dist") or []:
    q = Requirement(line)
    if q.marker is None or q.marker.evaluate({"extra": ""}):
        deps.append(q.name)
print(json.dumps({"name": m["Name"], "version": m["Version"], "deps": deps}))
`;

mkdirSync(TMP, { recursive: true });

const roues = new Map(); // normalised name -> { version, fichier, deps }
for (const [racine, spec] of RACINES) {
	const dir = join(TMP, racine);
	mkdirSync(dir, { recursive: true });
	console.log("pip download " + spec);
	py(["-m", "pip", "download", "--only-binary=:all:", "--platform", "win_amd64", "--python-version", "3.12",
		"--implementation", "cp", "--no-cache-dir", "-d", dir, spec]);
	for (const f of readdirSync(dir).filter((x) => x.endsWith(".whl"))) {
		const meta = JSON.parse(py(["-I", "-c", LIRE_ROUE, join(dir, f)]));
		const cle = norm(meta.name);
		const prev = roues.get(cle);
		if (prev && (prev.version !== meta.version || prev.fichier !== f))
			throw new Error("version conflict for " + cle + ": " + prev.fichier + " vs " + f);
		roues.set(cle, { version: meta.version, fichier: f, deps: [...new Set(meta.deps.map(norm))] });
	}
}

const paquets = {};
for (const cle of [...roues.keys()].sort()) {
	const w = roues.get(cle);
	const j = await (await fetch("https://pypi.org/pypi/" + cle + "/" + w.version + "/json")).json();
	const u = j.urls.find((x) => x.filename === w.fichier);
	if (!u) throw new Error("PyPI does not list " + w.fichier);
	const dependances = w.deps.filter((d) => roues.has(d)).sort();
	const absentes = w.deps.filter((d) => !roues.has(d));
	if (absentes.length) console.warn(cle + ": Requires-Dist true here but not downloaded by pip: " + absentes);
	paquets[cle] = { version: w.version, url: u.url, sha256: u.digests.sha256, taille: u.size, dependances };
}

console.log("downloading the interpreter");
const zip = Buffer.from(await (await fetch(URL_INTERPRETE)).arrayBuffer());
const interprete = {
	version: "3.12.10", url: URL_INTERPRETE,
	sha256: createHash("sha256").update(zip).digest("hex"), taille: zip.length,
};
const stdlib = JSON.parse(py(["-I", "-c", "import sys,json;print(json.dumps(sorted(sys.stdlib_module_names)))"]));

const ts = `/**
 * GENERATED by scripts/pin-python.mjs, do not edit by hand. Pinned CPython
 * interpreter and course wheels (win_amd64 / CPython 3.12).
 */
export const INTERPRETE_DATA = ${JSON.stringify(interprete, null, "\t")} as const;

export const PAQUETS_DATA: Record<string, { version: string; url: string; sha256: string; taille: number; dependances: readonly string[] }> = ${JSON.stringify(paquets, null, "\t")};

export const IMPORTS_DATA: Record<string, string> = ${JSON.stringify(IMPORTS, null, "\t")};

export const STDLIB_DATA: readonly string[] = ${JSON.stringify(stdlib)};
`;
mkdirSync(dirname(SORTIE), { recursive: true });
writeFileSync(SORTIE, ts);
const taille = (k) => Object.values(Object.fromEntries(fermeture(k).map((n) => [n, paquets[n]]))).reduce((s, p) => s + p.taille, 0);
function fermeture(k, vus = new Set()) { if (vus.has(k)) return []; vus.add(k); for (const d of paquets[k].dependances) fermeture(d, vus); return [...vus]; }
console.log("wrote " + SORTIE + "; torch closure " + fermeture("torch").length + " wheels, " + taille("torch") + " bytes");
